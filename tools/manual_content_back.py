    m.steps([
        "在分桌分配中切换到 **评审** 模式。",
        "从评审池拖拽桌长和参与评审到对应桌。",
        "拖到已有评审卡片上会替换该人员，系统会要求确认。",
        "检查每桌桌长、参与评审人数和利益冲突提示。",
        "保存评审人员。",
    ])
    m.callout("提示", "后续轮可以沿用首轮评审，也可以按现场情况调整。替换评审时务必确认，避免影响在评任务。")

    m.h2("8.5 发布排序轮")
    m.steps([
        "确认当前轮次为草稿状态。",
        "查看轮次检查：桌数、桌长、参与评审、酒款分配、排序名额。",
        "点击 **发布给桌长和参与评审**。",
        "确认发布后，桌长和参与评审在裁判 H5 看到排序任务。",
    ])
    m.screenshot("08-04", "发布排序轮",
                 "显示轮次检查结果和“发布给桌长和参与评审”按钮。",
                 "① 轮次检查 ② 发布按钮")

    m.h2("8.6 评委排序操作")
    m.p("排序轮中，桌长提交正式排序；参与评审可以保存参考排序。")
    m.h3("桌长")
    m.steps([
        "进入本桌排序任务。",
        "将候选酒款按顺序填入排序槽位。",
        "可扫码或输入短编号定位酒款。",
        "确认排序完整后点击 **提交同桌确认**。",
        "在确认框中核对排序结果并提交。",
    ])
    m.h3("参与评审")
    m.steps([
        "进入本桌排序任务。",
        "按自己的判断调整候选顺序。",
        "点击 **保存我的参考排序**。",
        "参考排序仅供本人参考，不作为最终结果。",
    ])
    m.callout("注意", "桌长在主办方锁定前仍可修改排序；重新提交会重置同桌确认，需要同桌评审再次确认。")
    m.screenshot("08-05", "桌长排序页",
                 "显示排序槽位、候选酒款、提交同桌确认按钮。",
                 "① 排序槽位 ② 候选酒款 ③ 提交同桌确认")
    m.screenshot("08-06", "参与评审参考排序",
                 "显示候选酒款和“保存我的参考排序”按钮。",
                 "① 参考排序 ② 保存")

    m.h2("8.7 同桌确认与主办方锁定")
    m.steps([
        "同桌评审进入 **本桌排序核对**。",
        "核对本桌排序结果。",
        "点击 **确认同意本桌排序**。",
        "主办方在比赛详情中查看各桌排序和确认状态。",
        "确认无误后点击 **确认排序并锁定**。",
    ])
    m.callout("注意", "锁定后排序结果用于生成奖项草稿。锁定前完成所有修改和确认。")
    m.screenshot("08-07", "排序同桌确认",
                 "显示本桌排序结果、确认状态和确认按钮。",
                 "① 排序结果 ② 确认状态 ③ 确认按钮")
    m.screenshot("08-08", "锁定排序轮",
                 "显示“确认排序并锁定”按钮和确认框。",
                 "① 轮次状态 ② 确认锁定")

    m.h2("8.8 多组别奖牌轮")
    m.p("组别金银铜轮允许一张评审桌包含多个组别。系统按组别分别排序和计奖，不能跨组别混排。")
    m.bullet("每张桌可以包含多个投递组别。")
    m.bullet("排序和奖项按组别隔离；同一桌的不同组别互不占用名次。")
    m.bullet("桌长提交的排序结果需要覆盖本桌所有组别的候选。")
    m.bullet("发布前检查每个组别的候选数量和排序名额。")
    m.callout("注意", "多组别同桌时，现场沟通要明确“按组别排序”。不要把不同组别的酒款放在同一条排序序列里比较。")

    m.h2("8.9 决赛轮（总冠军）")
    m.p("决赛轮只接收各组别奖牌轮产生的金奖，银奖和铜奖不进入总冠军候选。")
    m.steps([
        "确认组别金银铜轮已锁定并生成奖项。",
        "创建决赛轮，目标模式选择 **决赛轮**。",
        "在候选池中核对进入决赛的酒款，应该只包含各组别金奖。",
        "手动分桌并指定桌长和参与评审。",
        "发布后由桌长提交排序，完成同桌确认。",
        "主办方确认并锁定决赛轮。",
    ])
    m.callout("注意", "决赛轮候选仅限各组别金奖。如果候选池出现银奖或铜奖，先检查奖牌轮结果和奖项生成状态，不要直接发布。")

    m.h2("8.10 修改与重开")
    m.p("在主办方锁定前，桌长可以修改排序并重新提交，同桌确认会重置。锁定后原则上不能继续修改。")
    m.bullet("需要修改时，先在裁判 H5 重新提交排序，再完成同桌确认。")
    m.bullet("现场特殊情况需要调整已锁定结果时，按页面提供的重开或退回操作处理；没有入口时联系平台。")
    m.bullet("任何调整都要重新核对后续轮候选和奖项路径。")

    m.h2("8.11 常见问题")
    m.table(
        ["问题", "处理方式"],
        [
            ("候选池没有酒款", "确认上一轮已锁定、酒款已晋级；检查是否被取消或退款。"),
            ("候选不会自动上桌", "后续轮需要手动分桌，使用拖拽或快速分配加入。"),
            ("排序提交按钮不可用", "检查排序槽位是否填满、桌长是否已提交、同桌确认是否完成。"),
            ("同桌确认被重置", "桌长修改并重新提交后会重置，需要同桌再次确认。"),
            ("决赛轮出现银奖", "检查奖牌轮结果和奖项生成；决赛轮候选应仅为各组别金奖。"),
            ("锁定后还能改吗", "原则上不能；按页面重开流程或联系平台处理。"),
        ],
        widths=[5.2, 11.4],
    )

    m.page_break()


