def _apply_fonts_to_rpr(rpr, ascii_font, ea_font):
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), ascii_font)
    rfonts.set(qn("w:hAnsi"), ascii_font)
    rfonts.set(qn("w:eastAsia"), ea_font)


def _fmt_run(run, ascii_font, ea_font, size=None, bold=None, color=None, italic=None):
    run.font.name = ascii_font
    rpr = run._element.get_or_add_rPr()
    _apply_fonts_to_rpr(rpr, ascii_font, ea_font)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if italic is not None:
        run.font.italic = italic
    if color is not None:
        run.font.color.rgb = RGBColor(*color)


def _style_font(style, ascii_font, ea_font, size=None, bold=None, color=None):
    style.font.name = ascii_font
    if size is not None:
        style.font.size = Pt(size)
    if bold is not None:
        style.font.bold = bold
    if color is not None:
        style.font.color.rgb = RGBColor(*color)
    _apply_fonts_to_rpr(style.element.get_or_add_rPr(), ascii_font, ea_font)


