def h(text, level=1):
    p = doc.add_heading(level=level)
    r = p.add_run(text)
    _fmt_run(r, EA, EA, {1: 18, 2: 15, 3: 13.5}[level], True, HEAD_COLOR)
    return p


def p(text, bold=False, color=None, align=None, space_after=4):
    para = doc.add_paragraph()
    para.paragraph_format.space_after = Pt(space_after)
    if align is not None:
        para.alignment = align
    r = para.add_run(text)
    _fmt_run(r, BODY_ASCII, BODY_EA, 11, bold, color)
    return para


def bullets(items):
    for it in items:
        para = doc.add_paragraph()
        pf = para.paragraph_format
        pf.left_indent = Cm(0.75)
        pf.first_line_indent = Cm(-0.35)
        pf.space_after = Pt(2)
        r = para.add_run("•  " + it)
        _fmt_run(r, BODY_ASCII, BODY_EA, 11)


def steps(items):
    for i, it in enumerate(items, 1):
        para = doc.add_paragraph()
        pf = para.paragraph_format
        pf.left_indent = Cm(0.78)
        pf.first_line_indent = Cm(-0.78)
        pf.space_after = Pt(2)
        r = para.add_run(f"{i}. {it}")
        _fmt_run(r, BODY_ASCII, BODY_EA, 11)


def note(text):
    para = doc.add_paragraph()
    pf = para.paragraph_format
    pf.left_indent = Cm(0.3)
    pf.space_before = Pt(2)
    pf.space_after = Pt(8)
    r1 = para.add_run("注意：")
    _fmt_run(r1, BODY_ASCII, BODY_EA, 10.5, True, (0xB0, 0x1B, 0x1B))
    r2 = para.add_run(text)
    _fmt_run(r2, BODY_ASCII, BODY_EA, 10.5, False, (0x59, 0x59, 0x59))


def _shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcPr.append(shd)


def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, txt in enumerate(headers):
        _shade(hdr[i], "D9E2F3")
        para = hdr[i].paragraphs[0]
        para.paragraph_format.space_after = Pt(2)
        r = para.add_run(txt)
        _fmt_run(r, BODY_ASCII, BODY_EA, 10.5, True, HEAD_COLOR)
    for row in rows:
        cells = t.add_row().cells
        for i, txt in enumerate(row):
            para = cells[i].paragraphs[0]
            para.paragraph_format.space_after = Pt(2)
            r = para.add_run(str(txt))
            _fmt_run(r, BODY_ASCII, BODY_EA, 10.5)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def figure(caption, hint):
    """灰色截图占位框 + 下方居中的图题（图题无标点）。"""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = t.cell(0, 0)
    cell.width = Cm(15.5)
    _shade(cell, "F2F2F2")
    # 行高
    trPr = t.rows[0]._tr.get_or_add_trPr()
    trH = OxmlElement("w:trHeight")
    trH.set(qn("w:val"), "1400")
    trH.set(qn("w:hRule"), "atLeast")
    trPr.append(trH)
    p1 = cell.paragraphs[0]
    p1.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r1 = p1.add_run("【截图占位】")
    _fmt_run(r1, BODY_ASCII, EA, 11, True, GREY)
    p2 = cell.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run(hint)
    _fmt_run(r2, BODY_ASCII, BODY_EA, 9.5, False, GREY)
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_before = Pt(2)
    cap.paragraph_format.space_after = Pt(10)
    rc = cap.add_run(caption)
    _fmt_run(rc, BODY_ASCII, BODY_EA, 10, False, (0x40, 0x40, 0x40))
    return t


def add_page_number(paragraph):
    run = paragraph.add_run()
    _fmt_run(run, BODY_ASCII, BODY_EA, 9, False, GREY)
    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = "PAGE"
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    run._r.append(fld1)
    run._r.append(instr)
    run._r.append(fld2)


def add_toc(levels="1-3"):
    para = doc.add_paragraph()
    run = para.add_run()
    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = f'TOC \\o "{levels}" \\h \\z \\u'
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")
    placeholder = OxmlElement("w:t")
    placeholder.text = "（在 Word 中右键此处选择“更新域”即可生成目录）"
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    run._r.append(fld1)
    run._r.append(instr)
    run._r.append(fld_sep)
    run._r.append(placeholder)
    run._r.append(fld2)

